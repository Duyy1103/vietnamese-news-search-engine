"""Reusable search layer for BM25, E5/FAISS, and reciprocal-rank fusion."""

from __future__ import annotations

import json
import pickle
import unicodedata
from pathlib import Path
from typing import Literal

import numpy as np
import pandas as pd


LEXICAL_DIR = Path("data/indexes/lexical")
SEMANTIC_DIR = Path("data/embeddings/e5_base")
SEMANTIC_CONFIG_DIR = Path("data/embeddings/e5_4configs")
LOCAL_E5_DIR = Path("models/e5_base_offline")
STOPWORDS_PATH = Path("data/raw/vietnamese-stopwords.txt")


def remove_vietnamese_accents(text: str) -> str:
    normalized = unicodedata.normalize("NFD", text)
    without_marks = "".join(char for char in normalized if unicodedata.category(char) != "Mn")
    return without_marks.replace("\u0111", "d").replace("\u0110", "D")


def load_stopwords() -> set[str]:
    if not STOPWORDS_PATH.exists():
        raise FileNotFoundError(f"Stopword file not found: {STOPWORDS_PATH}")
    with STOPWORDS_PATH.open(encoding="utf-8") as file:
        return {
            line.strip().lower().replace(" ", "_")
            for line in file
            if line.strip() and not line.lstrip().startswith("#")
        }


class BM25Searcher:
    """Search documents using artefacts built by build_lexical_artifacts.py."""

    def __init__(self, artefact_dir: Path = LEXICAL_DIR) -> None:
        model_path = artefact_dir / "bm25_rank_bm25.pkl"
        documents_path = artefact_dir / "lexical_documents.parquet"
        if not model_path.exists() or not documents_path.exists():
            raise FileNotFoundError(
                "BM25 artefacts are missing. Run: "
                "python build_lexical_artifacts.py"
            )
        with model_path.open("rb") as file:
            self.model = pickle.load(file)
        self.documents = pd.read_parquet(documents_path)

    def search(self, query: str, top_k: int = 10) -> pd.DataFrame:
        tokens = str(query).strip().lower().split()
        if not tokens:
            return pd.DataFrame()
        scores = self.model.get_scores(tokens)
        top_indices = np.argsort(scores)[::-1][:top_k]
        results = self.documents.iloc[top_indices].copy()
        results["score"] = scores[top_indices]
        results["method"] = "bm25"
        return results.sort_values("score", ascending=False).reset_index(drop=True)


class SemanticSearcher:
    """Search chunk embeddings generated by the multilingual E5 model."""

    def __init__(self, artefact_dir: Path = SEMANTIC_DIR) -> None:
        index_path = artefact_dir / "semantic_e5_base.faiss"
        metadata_path = artefact_dir / "chunks_metadata.parquet"
        config_path = artefact_dir / "embedding_config.json"
        missing = [path for path in [index_path, metadata_path, config_path] if not path.exists()]
        if missing:
            raise FileNotFoundError(f"Semantic artefacts are missing: {missing}")

        import faiss

        self.index = faiss.read_index(str(index_path))
        self.metadata = pd.read_parquet(metadata_path)
        self.config = json.loads(config_path.read_text(encoding="utf-8"))
        self._tokenizer = None
        self._model = None
        self._torch = None
        self._device = None

    def _load_model(self) -> None:
        if self._model is not None:
            return
        import torch
        import torch.nn.functional as functional
        from transformers import AutoModel, AutoTokenizer

        self._torch = torch
        self._functional = functional
        self._device = "cuda" if torch.cuda.is_available() else "cpu"
        dtype = torch.float16 if self._device == "cuda" else torch.float32
        model_source = LOCAL_E5_DIR if LOCAL_E5_DIR.exists() else self.config["model_name"]
        self._tokenizer = AutoTokenizer.from_pretrained(model_source)
        self._model = AutoModel.from_pretrained(
            model_source, torch_dtype=dtype
        ).to(self._device)
        self._model.eval()

    def _encode_query(self, query: str) -> np.ndarray:
        self._load_model()
        assert self._torch is not None and self._tokenizer is not None and self._model is not None
        prefixed_query = self.config.get("query_prefix", "query: ") + query.strip()
        inputs = self._tokenizer(
            [prefixed_query],
            max_length=self.config.get("max_length", 512),
            padding=True,
            truncation=True,
            return_tensors="pt",
        )
        inputs = {key: value.to(self._device) for key, value in inputs.items()}
        with self._torch.no_grad():
            output = self._model(**inputs)
        mask = inputs["attention_mask"].unsqueeze(-1).expand(output.last_hidden_state.size()).float()
        pooled = (output.last_hidden_state.float() * mask).sum(dim=1) / mask.sum(dim=1).clamp(min=1e-9)
        normalized = self._functional.normalize(pooled, p=2, dim=1)
        return normalized.cpu().numpy().astype("float32")

    def search(
        self,
        query: str,
        top_k: int = 10,
        candidate_k: int | None = None,
        topic: str | None = None,
        min_score: float | None = None,
        group_by_document: bool = True,
    ) -> pd.DataFrame:
        if not str(query).strip():
            return pd.DataFrame()
        candidate_k = min(candidate_k or max(top_k * 5, 50), self.index.ntotal)
        scores, indices = self.index.search(self._encode_query(query), candidate_k)
        rows: list[dict] = []
        for score, index in zip(scores[0], indices[0]):
            if index < 0 or (min_score is not None and score < min_score):
                continue
            row = self.metadata.iloc[int(index)].to_dict()
            if topic and row.get("topic") != topic:
                continue
            row["score"] = float(score)
            row["method"] = "semantic_e5"
            rows.append(row)
            if not group_by_document and len(rows) >= top_k:
                break
        results = pd.DataFrame(rows)
        if results.empty:
            return results
        if group_by_document:
            results = (
                results.sort_values("score", ascending=False)
                .groupby("doc_id", as_index=False)
                .first()
                .sort_values("score", ascending=False)
                .head(top_k)
            )
        return results.reset_index(drop=True)


class SemanticConfigSearcher(SemanticSearcher):
    """Search a semantic index built for one preprocessing configuration."""

    def __init__(self, config_name: str, artefact_root: Path = SEMANTIC_CONFIG_DIR) -> None:
        self.config_name = config_name
        artefact_dir = artefact_root / config_name
        if not artefact_dir.exists():
            raise FileNotFoundError(
                f"Semantic config artefacts are missing for {config_name}. Run: "
                "python build_semantic_4configs.py"
            )
        super().__init__(artefact_dir)
        self.stopwords = load_stopwords()
        self.unaccented_stopwords = {remove_vietnamese_accents(word) for word in self.stopwords}

    def _preprocess_query(self, query: str) -> str:
        text = " ".join(str(query).strip().lower().split())
        if "unaccented" in self.config_name:
            text = remove_vietnamese_accents(text)
        if "no_stopwords" in self.config_name:
            stopwords = self.unaccented_stopwords if "unaccented" in self.config_name else self.stopwords
            text = " ".join(token for token in text.split() if token not in stopwords)
        return text

    def search(
        self,
        query: str,
        top_k: int = 10,
        candidate_k: int | None = None,
        topic: str | None = None,
        min_score: float | None = None,
        group_by_document: bool = True,
    ) -> pd.DataFrame:
        processed_query = self._preprocess_query(query)
        if not processed_query:
            return pd.DataFrame()
        results = super().search(
            processed_query,
            top_k=top_k,
            candidate_k=candidate_k,
            topic=topic,
            min_score=min_score,
            group_by_document=group_by_document,
        )
        if not results.empty:
            results["method"] = f"semanticcfg_{self.config_name}"
        return results


class TFIDFSearcher:
    """Search documents using pre-built TF-IDF index and cosine similarity."""

    def __init__(self, config_name: str, artefact_dir: Path = Path("data/indexes/tfidf")) -> None:
        self.config_name = config_name
        vec_path = artefact_dir / f"tfidf_vectorizer_{config_name}.pkl"
        mat_path = artefact_dir / f"tfidf_matrix_{config_name}.npz"
        idx_path = artefact_dir / f"inverted_index_{config_name}.pkl"
        
        if not all(p.exists() for p in [vec_path, mat_path, idx_path]):
            raise FileNotFoundError(f"TFIDF artefacts missing for {config_name}")
            
        with vec_path.open("rb") as f:
            self.vectorizer = pickle.load(f)
        
        from scipy.sparse import load_npz
        self.matrix = load_npz(mat_path)
        
        with idx_path.open("rb") as f:
            self.inverted_index = pickle.load(f)
            
        lexical_doc_path = Path("data/indexes/lexical/lexical_documents.parquet")
        self.documents = pd.read_parquet(lexical_doc_path)
        self.doc_id_to_idx = {str(row["doc_id"]): idx for idx, row in self.documents.iterrows()}
        
        self.stopwords = load_stopwords()
        self.unaccented_stopwords = {remove_vietnamese_accents(word) for word in self.stopwords}

    def _preprocess(self, query: str) -> str:
        text = str(query).strip().lower()
        if "unaccented" in self.config_name:
            text = remove_vietnamese_accents(text)
        
        if "no_stopwords" in self.config_name:
            tokens = text.split()
            stopwords = self.unaccented_stopwords if "unaccented" in self.config_name else self.stopwords
            text = " ".join([t for t in tokens if t not in stopwords])
            
        return text

    def search(self, query: str, top_k: int = 10) -> pd.DataFrame:
        processed_query = self._preprocess(query)
        query_tokens = self.vectorizer.build_analyzer()(processed_query)
        
        candidate_doc_ids = set()
        for token in query_tokens:
            if token in self.inverted_index:
                candidate_doc_ids.update(self.inverted_index[token])
                
        if not candidate_doc_ids:
            return pd.DataFrame()
            
        candidate_indices = [self.doc_id_to_idx[str(d_id)] for d_id in candidate_doc_ids if str(d_id) in self.doc_id_to_idx]
        if not candidate_indices:
            return pd.DataFrame()
            
        from sklearn.metrics.pairwise import cosine_similarity
        query_vector = self.vectorizer.transform([processed_query])
        sub_matrix = self.matrix[candidate_indices]
        similarities = cosine_similarity(query_vector, sub_matrix).flatten()
        
        top_k_sub = similarities.argsort()[-top_k:][::-1]
        
        results = []
        for rank, sub_idx in enumerate(top_k_sub):
            score = similarities[sub_idx]
            if score <= 0: continue
            original_idx = candidate_indices[sub_idx]
            row = self.documents.iloc[original_idx].copy()
            row["score"] = float(score)
            row["method"] = f"tfidf_{self.config_name}"
            results.append(row)
            
        if not results:
            return pd.DataFrame()
        return pd.DataFrame(results).sort_values("score", ascending=False).reset_index(drop=True)


class BM25ConfigSearcher:
    """Search documents using pre-built BM25 config artefacts (4 configs)."""

    def __init__(self, config_name: str, artefact_dir: Path = Path("data/indexes/bm25")) -> None:
        self.config_name = config_name
        bm25_path = artefact_dir / f"bm25_{config_name}.pkl"
        doc_ids_path = artefact_dir / "doc_ids.pkl"

        if not bm25_path.exists() or not doc_ids_path.exists():
            raise FileNotFoundError(f"BM25 config artefacts missing for {config_name}")

        with bm25_path.open("rb") as f:
            self.model = pickle.load(f)
        with doc_ids_path.open("rb") as f:
            self.doc_ids = pickle.load(f)

        lexical_doc_path = Path("data/indexes/lexical/lexical_documents.parquet")
        self.documents = pd.read_parquet(lexical_doc_path)
        self.doc_id_to_idx = {str(row["doc_id"]): idx for idx, row in self.documents.iterrows()}

        self.stopwords = load_stopwords()
        self.unaccented_stopwords = {remove_vietnamese_accents(word) for word in self.stopwords}

    def _preprocess(self, query: str) -> str:
        text = str(query).strip().lower()
        if "unaccented" in self.config_name:
            text = remove_vietnamese_accents(text)
        if "no_stopwords" in self.config_name:
            tokens = text.split()
            stopwords = self.unaccented_stopwords if "unaccented" in self.config_name else self.stopwords
            text = " ".join([t for t in tokens if t not in stopwords])
        return text

    def search(self, query: str, top_k: int = 10) -> pd.DataFrame:
        processed_query = self._preprocess(query)
        tokens = processed_query.split()
        if not tokens:
            return pd.DataFrame()
        scores = self.model.get_scores(tokens)
        top_indices = np.argsort(scores)[::-1][:top_k]

        results = []
        for idx in top_indices:
            score = scores[idx]
            if score <= 0:
                continue
            doc_id = self.doc_ids[idx]
            if doc_id in self.doc_id_to_idx:
                row = self.documents.iloc[self.doc_id_to_idx[doc_id]].copy()
            else:
                row = pd.Series({"doc_id": doc_id})
            row["score"] = float(score)
            row["method"] = f"bm25cfg_{self.config_name}"
            results.append(row)

        if not results:
            return pd.DataFrame()
        return pd.DataFrame(results).sort_values("score", ascending=False).reset_index(drop=True)


def reciprocal_rank_fusion(
    result_sets: dict[str, pd.DataFrame], top_k: int = 10, rrf_k: int = 60
) -> pd.DataFrame:
    """Merge rankings without comparing incompatible BM25 and cosine score scales."""
    fused: dict[str, dict] = {}
    for method, results in result_sets.items():
        if results.empty or "doc_id" not in results:
            continue
        for rank, (_, row) in enumerate(results.iterrows(), start=1):
            document_id = str(row["doc_id"])
            entry = fused.setdefault(document_id, {"doc_id": document_id, "score": 0.0, "methods": []})
            entry["score"] += 1.0 / (rrf_k + rank)
            entry["methods"].append(method)
            for key, value in row.items():
                if key not in entry and pd.notna(value):
                    entry[key] = value
    if not fused:
        return pd.DataFrame()
    results = pd.DataFrame(fused.values()).sort_values("score", ascending=False).head(top_k)
    results["method"] = "hybrid_rrf"
    return results.reset_index(drop=True)


class SearchEngine:
    """Lazy loader so semantic-only search does not require lexical artefacts and vice versa."""

    def __init__(self) -> None:
        self._bm25: BM25Searcher | None = None
        self._semantic: SemanticSearcher | None = None
        self._tfidf_searchers: dict[str, TFIDFSearcher] = {}
        self._bm25cfg_searchers: dict[str, BM25ConfigSearcher] = {}
        self._semanticcfg_searchers: dict[str, SemanticConfigSearcher] = {}

    @property
    def bm25(self) -> BM25Searcher:
        if self._bm25 is None:
            self._bm25 = BM25Searcher()
        return self._bm25

    @property
    def semantic(self) -> SemanticSearcher:
        if self._semantic is None:
            self._semantic = SemanticSearcher()
        return self._semantic

    def get_tfidf(self, config_name: str) -> TFIDFSearcher:
        if config_name not in self._tfidf_searchers:
            self._tfidf_searchers[config_name] = TFIDFSearcher(config_name)
        return self._tfidf_searchers[config_name]

    def get_bm25cfg(self, config_name: str) -> BM25ConfigSearcher:
        if config_name not in self._bm25cfg_searchers:
            self._bm25cfg_searchers[config_name] = BM25ConfigSearcher(config_name)
        return self._bm25cfg_searchers[config_name]

    def get_semanticcfg(self, config_name: str) -> SemanticConfigSearcher:
        if config_name not in self._semanticcfg_searchers:
            self._semanticcfg_searchers[config_name] = SemanticConfigSearcher(config_name)
        return self._semanticcfg_searchers[config_name]

    def search(
        self,
        query: str,
        mode: str = "semantic",
        top_k: int = 10,
        topic: str | None = None,
    ) -> pd.DataFrame:
        if mode == "bm25":
            return self.bm25.search(query, top_k)
        if mode == "semantic":
            return self.semantic.search(query, top_k, topic=topic)
        if mode == "hybrid":
            return reciprocal_rank_fusion(
                {
                    "bm25": self.bm25.search(query, top_k * 3),
                    "semantic_e5": self.semantic.search(query, top_k * 3, topic=topic),
                },
                top_k=top_k,
            )
        if mode.startswith("tfidf_"):
            config_name = mode.replace("tfidf_", "", 1)
            return self.get_tfidf(config_name).search(query, top_k)
        if mode.startswith("bm25cfg_"):
            config_name = mode.replace("bm25cfg_", "", 1)
            return self.get_bm25cfg(config_name).search(query, top_k)
        if mode.startswith("semanticcfg_"):
            config_name = mode.replace("semanticcfg_", "", 1)
            return self.get_semanticcfg(config_name).search(query, top_k, topic=topic)
        if mode.startswith("hybridcfg_"):
            config_name = mode.replace("hybridcfg_", "", 1)
            return reciprocal_rank_fusion(
                {
                    f"bm25cfg_{config_name}": self.get_bm25cfg(config_name).search(query, top_k * 3),
                    f"semanticcfg_{config_name}": self.get_semanticcfg(config_name).search(
                        query, top_k * 3, topic=topic
                    ),
                },
                top_k=top_k,
            )

        raise ValueError(f"Unsupported search mode: {mode}")
